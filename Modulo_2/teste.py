# Com o format
faturamento= 1000
custo= 400
lucro= faturamento - custo
print('O faturamneto da loja foi de {}. O custo da loja foi de {}. Assim o lucro foi de {}.'.format(faturamento, custo, lucro))

# Com f-string
faturamento= 1000
custo= 400
lucro= faturamento - custo
print(f'O faturamneto da loja foi de {faturamento}. O custo da loja foi de {custo}. Assim o lucro foi de {lucro}.')